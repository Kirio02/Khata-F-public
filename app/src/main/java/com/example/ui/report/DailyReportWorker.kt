class DailyReportWorker(
    context: Context,
    workerParams: WorkerParameters
) : CoroutineWorker(context, workerParams) {

    companion object {
        const val CHANNEL_ID = "daily_business_report_channel"
        const val NOTIFICATION_ID = 2026
        const val UNIQUE_WORK_NAME = "ghanshyam_daily_report_work"

        fun generateReportText(
            todaySales: Double,
            todayInvoicesCount: Int,
            todayCollected: Double,
            todayCreditGiven: Double,
            cashInHand: Double,
            topDebtors: List<Pair<String, Double>>
        ): String {
            val dateStr = SimpleDateFormat("dd MMM yyyy", Locale.US).format(Date())
            val sb = StringBuilder()
            sb.append("📊 GHANSHYAM DAILY BUSINESS REPORT\n")
            sb.append("═══════════════════════════════\n")
            sb.append("📅 Date: $dateStr\n\n")

            sb.append("💰 TODAY'S SUMMARY:\n")
            sb.append("• Sales: ₹${"%.2f".format(todaySales)} ($todayInvoicesCount bills)\n")
            sb.append("• Cash/UPI Collected: ₹${"%.2f".format(todayCollected)}\n")
            sb.append("• Credit Given (Udhar): ₹${"%.2f".format(todayCreditGiven)}\n")
            sb.append("• Net Cash in Hand: ₹${"%.2f".format(cashInHand)}\n\n")

            sb.append("👥 TOP PARTIES TO CHASE (Pending Udhar):\n")
            if (topDebtors.isEmpty()) {
                sb.append("• No pending debtors! All accounts clear.\n")
            } else {
                topDebtors.forEachIndexed { idx, (name, amt) ->
                    sb.append("${idx + 1}. $name: ₹${"%.2f".format(amt)}\n")
                }
            }

            sb.append("\n═══════════════════════════════\n")
            sb.append("Generated by Ghanshyam Billing")
            return sb.toString()
        }
    }

    override suspend fun doWork(): Result = withContext(Dispatchers.IO) {
        try {
            val db = AppDatabase.getInstance(applicationContext)

            // Calculate start and end of today
            val cal = Calendar.getInstance().apply {
                set(Calendar.HOUR_OF_DAY, 0)
                set(Calendar.MINUTE, 0)
                set(Calendar.SECOND, 0)
                set(Calendar.MILLISECOND, 0)
            }
            val startOfDay = cal.timeInMillis
            cal.add(Calendar.DAY_OF_YEAR, 1)
            val endOfDay = cal.timeInMillis

            // 1. Invoices today
            val allInvoices = db.invoiceDao().getAllWithItemsList()
            val todayInvoices = allInvoices.filter { it.invoice.date in startOfDay until endOfDay && !it.invoice.isCancelled }
            val todaySales = todayInvoices.sumOf { it.invoice.totalAmount }
            val todayInvoicesCount = todayInvoices.size

            // 2. Cashbook today & net cash in hand (CASH book only + opening balance)
            val settings = db.appSettingsDao().getSettingsDirect()
            val cashOpeningBalance = settings?.cashOpeningBalance ?: 0.0
            val allCash = db.cashbookDao().getAllList().filter { !it.isDeleted }
            val todayCashIn = allCash.filter { it.date in startOfDay until endOfDay && it.type == "IN" }.sumOf { it.amount }
            val totalCashIn = allCash.filter { it.bookType == "CASH" && it.type == "IN" }.sumOf { it.amount }
            val totalCashOut = allCash.filter { it.bookType == "CASH" && it.type == "OUT" }.sumOf { it.amount }
            val cashInHand = cashOpeningBalance + totalCashIn - totalCashOut

            // 3. Transactions today
            val allTx = db.transactionDao().getAllList()
            val todayCreditGiven = allTx.filter { it.date in startOfDay until endOfDay && it.type == "GAVE" && !com.example.data.OpeningBalance.isOpeningNote(it.note) }.sumOf { it.amount }

            // 4. Top 5 parties to chase & Overdue parties (positive gave - got = party owes us)
            val allCustomers = db.customerDao().getAllList()
            val debtorList = allCustomers.map { cust ->
                val custTx = allTx.filter { it.customerId == cust.id }
                val gave = custTx.filter { it.type == "GAVE" }.sumOf { it.amount }
                val got = custTx.filter { it.type == "GOT" }.sumOf { it.amount }
                val balance = gave - got
                cust to balance
            }.filter { it.second > 0.01 }
             .sortedByDescending { it.second }

            // Overdue = a bill that is still unpaid and past its due date / older than 15 days
            // (same rule as the Khata screen, so people who already paid are never chased).
            val txByCustomer = allTx.map { it.toDomain() }.groupBy { it.customerId }
            val overdueParties = debtorList.filter { (cust, _) ->
                com.example.data.OverdueLogic.isOverdue(txByCustomer[cust.id] ?: emptyList())
            }

            val topDebtors = debtorList.map { it.first.name to it.second }.take(5)

            val reportContent = generateReportText(
                todaySales = todaySales,
                todayInvoicesCount = todayInvoicesCount,
                todayCollected = todayCashIn,
                todayCreditGiven = todayCreditGiven,
                cashInHand = cashInHand,
                topDebtors = topDebtors
            )

            // Primary overdue party for direct 1-tap WhatsApp reminder
            val primaryOverduePair = overdueParties.firstOrNull() ?: debtorList.firstOrNull()
            sendNotification(reportContent, primaryOverduePair?.first, primaryOverduePair?.second ?: 0.0)
            Result.success()
        } catch (e: Exception) {
            android.util.Log.e("DailyReportWorker", "Error executing daily report: ${e.message}", e)
            Result.retry()
        }
    }

    private fun sendNotification(reportText: String, overdueCustomer: com.example.data.local.CustomerEntity? = null, overdueAmount: Double = 0.0) {
        val manager = applicationContext.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager

        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            val channel = NotificationChannel(
                CHANNEL_ID,
                "Daily Business Report & Due Date Reminders",
                NotificationManager.IMPORTANCE_HIGH
            ).apply {
                description = "Daily sales, udhar, and due date reminders"
                enableVibration(true)
            }
            manager.createNotificationChannel(channel)
        }

        val tapIntent = Intent(applicationContext, MainActivity::class.java).apply {
            flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP
            putExtra("OPEN_SCREEN", "AI")
            putExtra("DAILY_REPORT_CONTENT", reportText)
        }

        val pendingIntent = PendingIntent.getActivity(
            applicationContext,
            NOTIFICATION_ID,
            tapIntent,
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
        )

        val notifBuilder = NotificationCompat.Builder(applicationContext, CHANNEL_ID)
            .setSmallIcon(R.drawable.ic_notification)
            .setContentTitle("📊 Ghanshyam Daily Business Report")
            .setContentText("Tap to view today's complete sales, cashbook & udhar report")
            .setStyle(NotificationCompat.BigTextStyle().bigText(reportText))
            .setPriority(NotificationCompat.PRIORITY_HIGH)
            .setContentIntent(pendingIntent)
            .setAutoCancel(true)

        // If an overdue customer exists, add a 1-tap WhatsApp reminder action!
        if (overdueCustomer != null && overdueCustomer.phone.isNotBlank()) {
            val phoneNormalized = com.example.ui.util.PhoneUtil.toWhatsAppNumber(overdueCustomer.phone)
            val msgText = "Namaste ${overdueCustomer.name} ji, Ghanshyam Kids Wear se aapka ₹${"%.0f".format(overdueAmount)} ka hisaab baaki hai. Kripya payment kar dein."
            val encodedMsg = java.net.URLEncoder.encode(msgText, "UTF-8")
            val waUri = android.net.Uri.parse("https://api.whatsapp.com/send?phone=$phoneNormalized&text=$encodedMsg")
            val waIntent = Intent(Intent.ACTION_VIEW, waUri).apply {
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }
            val waPendingIntent = PendingIntent.getActivity(
                applicationContext,
                NOTIFICATION_ID + 1,
                waIntent,
                PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
            )
            notifBuilder.addAction(
                android.R.drawable.ic_dialog_email,
                "WhatsApp: ${overdueCustomer.name}",
                waPendingIntent
            )
        }

        manager.notify(NOTIFICATION_ID, notifBuilder.build())
    }
}
